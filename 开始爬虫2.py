# 第 2 课：亲手发一个 HTTP 请求（不用任何爬虫库）
#
# 这节课是整套教程的“地基”。看完你会发现：
#   爬虫没有魔法，它就是【发一段文字出去，收一段文字回来】。
#   requests 那个库，只是帮你把下面这几行包装得好看一点。
#
# 运行：python 02_亲手发一个HTTP请求.py

import socket   # Python 自带的“电话机”，能直接连到另一台电脑
import ssl      # 自带的安全层。因为网址是 https，相当于通话要加密

# 第 1 步：把网址变成 IP 地址
# ----------------------------------------------------------------------
# 网址（域名）是给人看的，电脑只认 IP（一串数字）。
# 这一步叫 DNS 解析，相当于“查电话簿”。

ip = socket.gethostbyname('quotes.toscrape.com')      
print(ip)


# 第 2 步：拨号连接
# ----------------------------------------------------------------------
# 443 是 https 的“门牌号”（端口号）。http 是 80。
# 可以理解为：IP 是大楼地址，端口是大楼里的房间号

sock = socket.create_connection(('quotes.toscrape.com', 443), timeout=10)

# https 要把这根线加密，这两行就是“上个锁”。
# 不懂没关系，记住：http 直接连，https 多这两
sock = ssl.create_default_context().wrap_socket(sock, server_hostname='quotes.toscrape.com')
print('连接成功')


# 第 3 步：自己拼一段“请求文字”发过去
# ----------------------------------------------------------------------
# 下面这几行，就是浏览器点开网页时，偷偷发给服务器的东西。
# \r\n 是“换行”（回车+换行），HTTP 协议规定每一行都要用它结尾。
#
#   第一行：我要用什么方式、要哪个文件、用哪个版本的协议
#   第二行：Host 我要访问哪个网站（一台服务器上可能放很多网站）
#   第三行：聊完就断开
#   第四行：空的 —— 这个空行非常重要，它表示“我说完了”

request = (
    'GET / HTTP/1.1\r\n'
    'Host: quotes.toscrape.com\r\n'
    'Connection: close\r\n'
    '\r\n'
)

# 把文字变成“字节”再发（网络只认字节，b"..." 就是字节写法）
# 这一行如果写错一个换行，服务器就会一直等你说完 —— 这就是“请求卡住”的真相

sock.sendall(request.encode('utf-8'))
print('请求已发送,内容就是这段文字')
print(request)


# 第 4 步：把服务器回的文字全部收下来

data = b""  # 准备一个空盒子
while True:
    chunk = sock.recv(4096)  # 一次收 4096 字节
    if not chunk:            # 收到空的了，说明对方说完了
        break
    data += chunk            # 把这一段拼到盒子里

sock.close()  # 挂电话
print("4. 一共收到", len(data), "字节")


# 第 5 步：看看服务器到底回了什么
# ----------------------------------------------------------------------
# 服务器回的东西分两部分：
#   前面几行是“说明书”（响应头）：状态、类型、长度……
#   空行之后才是网页正文。
text = data.decode("utf-8", "replace")  # 字节变回文字

print()
print("--------- 服务器回的原文（前 500 个字符）---------")
print(text[:500])

# 用空行把“说明书”和“正文”切开来看看
head, body = text.split("\r\n\r\n", 1)
print()
print("--------- 前半部分：说明书（响应头）---------")
print(head)
print()
print("--------- 后半部分：网页正文（前 200 字）---------")
print(body[:200])

print()
print(">>> 一句话总结：爬虫 = 拼一段文字发出去 + 收一段文字回来。")
print(">>> requests.get() 做的，就是这 5 步，一行顶 20 行。")
